#!/usr/bin/env node
// Builds the phone-friendly online preview: the V29 client plus the unmodified Worker API running in the
// browser (see runtime.js). Output is a folder that a static host or a claude.ai Artifact can serve.
// Usage: node tools/online-preview/build.cjs [outputDir]   (default: build/online-preview)
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const repo=path.resolve(__dirname,'..','..'),web=path.join(repo,'web-source'),dist=path.join(web,'dist');
const out=path.resolve(process.argv[2]||path.join(repo,'build','online-preview'));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');

// 1. Static client files, minus the server bundle, PDFs and the Android package (not usable in a browser preview).
fs.rmSync(out,{recursive:true,force:true});
const skip=rel=>/^(server|\.openai|releases)(\/|$)/.test(rel)||/\.pdf$/i.test(rel)||rel==='index.html'||rel==='client.html'||rel==='admin.html';
(function copy(dir,rel=''){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
    const r=rel+entry.name;if(skip(r))continue;
    if(entry.isDirectory())copy(path.join(dir,entry.name),r+'/');
    else if(entry.isFile()){fs.mkdirSync(path.join(out,rel),{recursive:true});fs.copyFileSync(path.join(dir,entry.name),path.join(out,r));}
  }
})(dist);

// 2. Backend bundle: same concatenation as scripts/build-worker.cjs, wrapped in one classic script.
const strip=src=>src.replace(/^export\s+(?=(?:async\s+)?function|const|class)/gm,'');
let api=fs.readFileSync(path.join(web,'worker/community.mjs'),'utf8');
api=api.replace(/^import\s+\{[^}]+\}\s+from\s+'\.\/(?:lessons|video-inspection)\.mjs';?\s*$/gm,'');
api=strip(fs.readFileSync(path.join(web,'worker/video-inspection.mjs'),'utf8'))+'\n'+strip(fs.readFileSync(path.join(web,'worker/lessons.mjs'),'utf8'))+'\n'+strip(api);
if(/^\s*(?:import|export)\s/m.test(api))throw Error('Worker API still has module syntax');
const sandbox={window:{}};vm.runInNewContext(fs.readFileSync(path.join(dist,'seed.js'),'utf8'),sandbox,{timeout:1000});
const seed=Object.values(sandbox.window).find(v=>v&&Array.isArray(v.songs));
const catalog=seed.songs.map(s=>({id:s.id,title:s.title,titles:s.titles,author:s.author,category:s.category,regions:s.regions,rightsStatus:s.rights?.status||'pending'}));
const lessonBox={window:{}};vm.runInNewContext(fs.readFileSync(path.join(dist,'lesson-data.js'),'utf8'),lessonBox,{timeout:1000});
const journal=JSON.parse(fs.readFileSync(path.join(web,'drizzle/meta/_journal.json'),'utf8'));
const migrations=journal.entries.map(e=>{const sql=fs.readFileSync(path.join(web,'drizzle',e.tag+'.sql'),'utf8');return {tag:e.tag,hash:sha(sql),sql};});
const backend='/* Generated by tools/online-preview/build.cjs from web-source/worker and runtime.js. Do not edit. */\n(function(){\'use strict\';\n'
  +api+'\nconst CATALOG_SOURCE='+JSON.stringify(catalog)+';\nconst LESSON_SOURCE='+JSON.stringify(lessonBox.window.SVLessonData?.lessons||[])
  +';\nconst LESSON_MEDIA_PATHS=[];\nconst SVP_MIGRATIONS='+JSON.stringify(migrations)+';\n'
  +fs.readFileSync(path.join(__dirname,'runtime.js'),'utf8')+'\n})();\n';
fs.writeFileSync(path.join(out,'preview-backend.js'),backend);
fs.mkdirSync(path.join(out,'vendor'),{recursive:true});
for(const f of ['sql-asm.js','LICENSE-sql.js.txt'])fs.copyFileSync(path.join(__dirname,'vendor',f),path.join(out,'vendor',f));

// 3. Pages. The Artifact host wraps the main page in its own <!doctype>/<head>/<body>, so page.html is the
// body content with the head's links first (the host publishes it as index.html); index.html here wraps the
// same content as a complete document for any other static host.
const index=fs.readFileSync(path.join(dist,'index.html'),'utf8');
const head=index.match(/<head>([\s\S]*?)<\/head>/)[1],body=index.match(/<body>([\s\S]*?)<\/body>/)[1];
const links=(head.match(/<link [^>]*rel="(?:icon|stylesheet)"[^>]*>/g)||[]).join('\n');
const sheet=fs.readFileSync(path.join(__dirname,'sheet.html'),'utf8');
const page=['<title>Silvio V29 在线预览</title>','<meta name="description" content="Silvio 电子小提琴 App V29 在线预览：客户端与服务端接口都在浏览器内运行。">',
  '<meta name="theme-color" content="#f7f6f2">',links,'<script src="vendor/sql-asm.js"></script>','<script src="preview-backend.js"></script>',body.trim(),sheet].join('\n')+'\n';
fs.writeFileSync(path.join(out,'page.html'),page);
fs.writeFileSync(path.join(out,'index.html'),'<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style></head><body>\n'+page+'</body></html>\n');
let admin=fs.readFileSync(path.join(dist,'admin.html'),'utf8');
admin=admin.replace('<head>','<head><script src="vendor/sql-asm.js"></script><script src="preview-backend.js"></script>');
// The admin page uses root-relative paths; make them relative so it works under any serving prefix.
admin=admin.replace(/(href|src)="\/(?!\/)/g,'$1="./').replaceAll('href="./#home"','href="index.html#home"');
fs.writeFileSync(path.join(out,'admin.html'),admin);
fs.writeFileSync(path.join(out,'admin.js'),fs.readFileSync(path.join(out,'admin.js'),'utf8').replaceAll('"/brands/','"brands/'));

const files=[];(function list(dir,rel=''){for(const e of fs.readdirSync(dir,{withFileTypes:true})){const r=rel+e.name;if(e.isDirectory())list(path.join(dir,e.name),r+'/');else files.push(r);}})(out);
const bytes=files.reduce((n,f)=>n+fs.statSync(path.join(out,f)).size,0);
console.log(JSON.stringify({out,files:files.length,megabytes:+(bytes/1048576).toFixed(2),catalog:catalog.length,migrations:migrations.length}));
